const ACTIVE_LOCALES = new Set<LangLocale>(
  LANG_REGISTRY.map((e) => e.i18nKey),
);

export function buildMarketingCopyBundle(): Record<string, MarketingCopy> {
  const bundle: Record<string, MarketingCopy> = {
    id: { ...MARKETING_COPY_ID },
    en: { ...MARKETING_COPY_EN },
  };

  for (const [locale, overlay] of Object.entries(MARKETING_LOCALE_FULL)) {
    if (!ACTIVE_LOCALES.has(locale as LangLocale)) continue;
    bundle[locale] = deepMerge(MARKETING_COPY_EN, overlay);
  }

  return bundle;
}

export function resolveMarketingLocale(countryCode: string): LangLocale {
  const entry = LANG_REGISTRY.find((e) => e.code === countryCode);
  return entry?.i18nKey ?? "en";
}
